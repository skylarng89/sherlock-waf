// Command refgen writes the API reference from api/openapi.yaml, so the
// documentation cannot drift from the contract the server enforces. Run it with
// `make gen`; CI fails if the committed file differs.
//
//	refgen <openapi.yaml> <output file>
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

type doc struct {
	Info struct {
		Title       string `yaml:"title"`
		Version     string `yaml:"version"`
		Description string `yaml:"description"`
	} `yaml:"info"`
	Servers []struct {
		URL string `yaml:"url"`
	} `yaml:"servers"`
	Tags []struct {
		Name string `yaml:"name"`
	} `yaml:"tags"`
	Paths      map[string]map[string]yaml.Node `yaml:"paths"`
	Components struct {
		Parameters map[string]param    `yaml:"parameters"`
		Responses  map[string]response `yaml:"responses"`
	} `yaml:"components"`
}

type param struct {
	Ref         string `yaml:"$ref"`
	Name        string `yaml:"name"`
	In          string `yaml:"in"`
	Required    bool   `yaml:"required"`
	Description string `yaml:"description"`
	Schema      schema `yaml:"schema"`
}

type schema struct {
	Ref    string   `yaml:"$ref"`
	Type   string   `yaml:"type"`
	Format string   `yaml:"format"`
	Enum   []string `yaml:"enum"`
	Items  *schema  `yaml:"items"`
}

type response struct {
	Ref         string `yaml:"$ref"`
	Description string `yaml:"description"`
}

type operation struct {
	ID          string              `yaml:"operationId"`
	Tags        []string            `yaml:"tags"`
	Summary     string              `yaml:"summary"`
	Description string              `yaml:"description"`
	Permission  string              `yaml:"x-sherlock-permission"`
	Parameters  []param             `yaml:"parameters"`
	RequestBody *body               `yaml:"requestBody"`
	Responses   map[string]response `yaml:"responses"`
	Deprecated  bool                `yaml:"deprecated"`
}

type body struct {
	Required bool `yaml:"required"`
	Content  map[string]struct {
		Schema schema `yaml:"schema"`
	} `yaml:"content"`
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: refgen <openapi.yaml> <output file>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, "refgen:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	raw, err := os.ReadFile(in) //nolint:gosec // build-time tool, path from the Makefile
	if err != nil {
		return err
	}
	var d doc
	if err := yaml.Unmarshal(raw, &d); err != nil {
		return err
	}
	return os.WriteFile(out, []byte(render(&d)), 0o644) //nolint:gosec // generated public docs file
}

type entry struct {
	method, path string
	op           operation
}

var methodOrder = map[string]int{"get": 0, "post": 1, "put": 2, "patch": 3, "delete": 4}

func render(d *doc) string {
	byTag := map[string][]entry{}
	for path, item := range d.Paths {
		for method, node := range item {
			if _, ok := methodOrder[method]; !ok {
				continue
			}
			var op operation
			if err := node.Decode(&op); err != nil {
				continue
			}
			tag := "other"
			if len(op.Tags) > 0 {
				tag = op.Tags[0]
			}
			byTag[tag] = append(byTag[tag], entry{method, path, op})
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# %s reference\n\n", strings.TrimSuffix(d.Info.Title, " API")+" API")
	b.WriteString("<!-- Generated by `make gen` from api/openapi.yaml. Do not edit. -->\n\n")
	base := "/"
	if len(d.Servers) > 0 {
		base = d.Servers[0].URL
	}
	fmt.Fprintf(&b, "Version %s. Every path below is relative to `%s`.\n\n", d.Info.Version, base)
	b.WriteString(strings.TrimSpace(d.Info.Description) + "\n\n")
	b.WriteString("Authentication is a dashboard session cookie (non-GET requests also need the `X-CSRF-Token` header) or an API token sent as `Authorization: Bearer shk_<id>_<secret>`. The permission column names what the caller needs; `public` needs none. The full schemas are in [api/openapi.yaml](../../api/openapi.yaml).\n\n")
	tags := make([]string, 0, len(byTag))
	for _, t := range d.Tags {
		if _, ok := byTag[t.Name]; ok {
			tags = append(tags, t.Name)
		}
	}
	var rest []string
	for t := range byTag {
		if !contains(tags, t) {
			rest = append(rest, t)
		}
	}
	sort.Strings(rest)
	tags = append(tags, rest...)
	for _, tag := range tags {
		es := byTag[tag]
		sort.Slice(es, func(i, j int) bool {
			if es[i].path != es[j].path {
				return es[i].path < es[j].path
			}
			return methodOrder[es[i].method] < methodOrder[es[j].method]
		})
		fmt.Fprintf(&b, "## %s\n\n", tag)
		for _, e := range es {
			writeOp(&b, d, e)
		}
	}
	return b.String()
}

func writeOp(b *strings.Builder, d *doc, e entry) {
	fmt.Fprintf(b, "### `%s %s`\n\n", strings.ToUpper(e.method), e.path)
	if e.op.Deprecated {
		b.WriteString("**Deprecated.**\n\n")
	}
	if e.op.Summary != "" {
		b.WriteString(e.op.Summary + "\n\n")
	}
	if e.op.Description != "" {
		b.WriteString(strings.TrimSpace(e.op.Description) + "\n\n")
	}
	fmt.Fprintf(b, "Operation `%s`. Permission: `%s`.\n\n", e.op.ID, e.op.Permission)
	item := d.Paths[e.path]
	var params []param
	if n, ok := item["parameters"]; ok {
		_ = n.Decode(&params)
	}
	params = append(params, e.op.Parameters...)
	if len(params) > 0 {
		b.WriteString("| Parameter | In | Type | Required | Description |\n| --- | --- | --- | --- | --- |\n")
		for _, p := range params {
			if p.Ref != "" {
				p = d.Components.Parameters[lastSegment(p.Ref)]
			}
			fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s |\n", p.Name, p.In, schemaLabel(p.Schema), yesNo(p.Required), oneLine(p.Description))
		}
		b.WriteString("\n")
	}
	if rb := e.op.RequestBody; rb != nil {
		for ct, c := range rb.Content {
			fmt.Fprintf(b, "Request body (`%s`%s): %s\n\n", ct, map[bool]string{true: ", required"}[rb.Required], schemaLabel(c.Schema))
		}
	}
	codes := make([]string, 0, len(e.op.Responses))
	for c := range e.op.Responses {
		codes = append(codes, c)
	}
	sort.Strings(codes)
	if len(codes) > 0 {
		b.WriteString("| Status | Meaning |\n| --- | --- |\n")
		for _, c := range codes {
			r := e.op.Responses[c]
			desc := r.Description
			if r.Ref != "" {
				desc = d.Components.Responses[lastSegment(r.Ref)].Description
			}
			fmt.Fprintf(b, "| %s | %s |\n", c, oneLine(desc))
		}
		b.WriteString("\n")
	}
}

func schemaLabel(s schema) string {
	switch {
	case s.Ref != "":
		return "`" + lastSegment(s.Ref) + "`"
	case s.Type == "array" && s.Items != nil:
		return "list of " + schemaLabel(*s.Items)
	case len(s.Enum) > 0:
		q := make([]string, len(s.Enum))
		for i, v := range s.Enum {
			q[i] = "`" + v + "`"
		}
		return "one of " + strings.Join(q, ", ")
	case s.Type != "":
		if s.Format != "" {
			return s.Type + " (" + s.Format + ")"
		}
		return s.Type
	}
	return "any"
}

func lastSegment(ref string) string { return ref[strings.LastIndex(ref, "/")+1:] }

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}

func oneLine(s string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(s), " "), "|", "\\|")
}

func contains(v []string, s string) bool {
	for _, x := range v {
		if x == s {
			return true
		}
	}
	return false
}
