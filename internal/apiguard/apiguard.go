// Package apiguard keeps a public Go package's exported API honest. It renders
// the exported surface (constants, variables, types with their exported fields
// and methods, functions, with signatures but no bodies or comments) from source
// and compares it with a committed golden file, so a change to a frozen package
// is always a deliberate, reviewable edit of that file.
package apiguard

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/doc"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

var update = flag.Bool("update", false, "rewrite the API golden file instead of comparing with it")

// Surface renders the exported API of the Go package in dir (test files are
// ignored). The output is stable: declarations are sorted by kind and name.
func Surface(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	fset := token.NewFileSet()
	var files []*ast.File
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return "", err
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return "", fmt.Errorf("no Go files in %s", dir)
	}
	pkg, err := doc.NewFromFiles(fset, files, "example.invalid/"+files[0].Name.Name, doc.AllDecls)
	if err != nil {
		return "", err
	}

	var entriesOut []string
	add := func(kind, name string, node ast.Node) error {
		var b bytes.Buffer
		if err := format.Node(&b, fset, node); err != nil {
			return err
		}
		entriesOut = append(entriesOut, kind+" "+name+"\n"+strings.TrimSpace(b.String())+"\n")
		return nil
	}
	exported := func(d ast.Decl) (ast.Decl, bool) {
		if !ast.FilterDecl(d, ast.IsExported) {
			return nil, false
		}
		return d, true
	}
	genDecl := func(kind string, d *ast.GenDecl, name string) error {
		d.Doc = nil
		stripGenDocs(d)
		if _, ok := exported(d); !ok {
			return nil
		}
		return add(kind, name, d)
	}
	funcDecl := func(kind string, d *ast.FuncDecl, name string) error {
		d.Doc, d.Body = nil, nil
		return add(kind, name, d)
	}

	for _, v := range pkg.Consts {
		if err := genDecl("const", v.Decl, strings.Join(v.Names, ",")); err != nil {
			return "", err
		}
	}
	for _, v := range pkg.Vars {
		if err := genDecl("var", v.Decl, strings.Join(v.Names, ",")); err != nil {
			return "", err
		}
	}
	for _, f := range pkg.Funcs {
		if err := funcDecl("func", f.Decl, f.Name); err != nil {
			return "", err
		}
	}
	for _, t := range pkg.Types {
		if !ast.IsExported(t.Name) {
			continue
		}
		if err := genDecl("type", t.Decl, t.Name); err != nil {
			return "", err
		}
		for _, v := range t.Consts {
			if err := genDecl("const", v.Decl, strings.Join(v.Names, ",")); err != nil {
				return "", err
			}
		}
		for _, v := range t.Vars {
			if err := genDecl("var", v.Decl, strings.Join(v.Names, ",")); err != nil {
				return "", err
			}
		}
		for _, f := range t.Funcs {
			if err := funcDecl("func", f.Decl, f.Name); err != nil {
				return "", err
			}
		}
		for _, m := range t.Methods {
			if !ast.IsExported(m.Name) {
				continue
			}
			if err := funcDecl("method", m.Decl, t.Name+"."+m.Name); err != nil {
				return "", err
			}
		}
	}
	sort.Strings(entriesOut)
	return "// Exported API surface of the package. Generated by internal/apiguard; do not edit by hand.\n\n" + strings.Join(entriesOut, "\n"), nil
}

// stripGenDocs removes comments inside a declaration so only the API remains.
func stripGenDocs(d *ast.GenDecl) {
	for _, s := range d.Specs {
		switch s := s.(type) {
		case *ast.TypeSpec:
			s.Doc, s.Comment = nil, nil
			stripFields(s.Type)
		case *ast.ValueSpec:
			s.Doc, s.Comment = nil, nil
		}
	}
}

func stripFields(e ast.Expr) {
	var fl *ast.FieldList
	switch t := e.(type) {
	case *ast.StructType:
		fl = t.Fields
	case *ast.InterfaceType:
		fl = t.Methods
	}
	if fl == nil {
		return
	}
	for _, f := range fl.List {
		f.Doc, f.Comment = nil, nil
	}
}

// Check compares the surface of the package in dir with golden (a path relative
// to the test's working directory). With -update it rewrites the file. A
// mismatch fails with the diff-relevant text and the command to regenerate it.
func Check(t testing.TB, dir, golden string) {
	t.Helper()
	got, err := Surface(dir)
	if err != nil {
		t.Fatal(err)
	}
	if *update {
		if err := os.MkdirAll(filepath.Dir(golden), 0o755); err != nil { //nolint:gosec // test data directory
			t.Fatal(err)
		}
		if err := os.WriteFile(golden, []byte(got), 0o644); err != nil { //nolint:gosec // committed golden file
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(golden) //nolint:gosec // committed golden file
	if err != nil {
		t.Fatalf("reading %s: %v\nCreate it with: go test . -run APIGuard -update", golden, err)
	}
	if string(want) != got {
		t.Fatalf("the exported API changed.\n\nThis package is a frozen public contract (docs/release/versioning.md). A breaking change needs a new major version; an addition is allowed but must be deliberate.\nIf the change is intended, regenerate the golden file and review the diff:\n\n    go test . -run APIGuard -update\n\n--- committed (%s)\n%s\n--- current\n%s", golden, want, got)
	}
}
